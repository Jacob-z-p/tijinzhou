DELIMITER $$

CREATE PROCEDURE seed_bank(IN p_title VARCHAR(256), IN p_description TEXT)
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM question_bank WHERE title = p_title AND is_delete = 0
    ) THEN
        SET @id_seq = @id_seq + 1;
        INSERT INTO question_bank (id, title, description, user_id)
        VALUES (@id_seq, p_title, p_description, @uid);
    END IF;
END$$

CREATE PROCEDURE seed_question(
    IN p_bank_title VARCHAR(256),
    IN p_title VARCHAR(256),
    IN p_content TEXT,
    IN p_tags VARCHAR(512),
    IN p_answer TEXT,
    IN p_status TINYINT
)
BEGIN
    DECLARE v_bank_id BIGINT;
    DECLARE v_question_id BIGINT;

    SELECT id INTO v_bank_id
    FROM question_bank
    WHERE title = p_bank_title AND is_delete = 0
    LIMIT 1;

    IF v_bank_id IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'question bank not found';
    END IF;

    SELECT id INTO v_question_id
    FROM question
    WHERE title = p_title AND is_delete = 0
    LIMIT 1;

    IF v_question_id IS NULL THEN
        SET @id_seq = @id_seq + 1;
        INSERT INTO question (id, title, content, tags, answer, user_id, status)
        VALUES (@id_seq, p_title, p_content, CAST(p_tags AS JSON), p_answer, @uid, p_status);
        SET v_question_id = @id_seq;
    END IF;

    SET @id_seq = @id_seq + 1;
    INSERT IGNORE INTO question_bank_question (id, question_bank_id, question_id, user_id)
    VALUES (@id_seq, v_bank_id, v_question_id, @uid);
END$$

